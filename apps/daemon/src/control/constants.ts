/**
 * 控制平面的固定取值（LWB-012）。
 *
 * 集中放一处，是因为这些值在**判定**与**生成**两侧都要用，
 * 而两侧对不上时的失效是静默的：例如 cookie 名写错一处，
 * 会话就永远建立不起来，但不会有任何检查报错。
 */

/**
 * 绑定的地址。**只有这一个字面量**，没有配置项。
 *
 * 不做成可配置的原因不是懒：「控制 API 只绑回环」是 LWB-012 的验收前提，
 * 而一个「允许绑到 0.0.0.0」的配置项迟早会有人在容器里、在
 * 「就想用手机看一眼」的时候打开它。届时验收标准 1 与 2 会同时失效，
 * 而代码里没有任何一处看起来像被改坏。
 *
 * 用 IPv4 字面量而不是 `localhost`：后者要经过名称解析，
 * 而解析结果可以被 hosts 文件、DNS 甚至 `HOSTALIASES` 改到别处。
 * 我们要绑的是「这台机器的回环接口」，那就直接说它的地址。
 */
export const CONTROL_BIND_HOST = '127.0.0.1';

/**
 * cookie 名与 CSRF 头名放在 `@lwb/contracts`，因为**控制台一侧也要用**
 * （它要读 CSRF 头的名字来发请求、要读 cookie 名来清除）。两处各写一份，
 * 就会有一天只改了一边 —— 而那一天不会有任何测试失败。
 * 这里只做转出，不重新定义。
 */
export { CONTROL_COOKIE_NAME, CONTROL_CSRF_HEADER } from '@lwb/contracts';

/** 请求体的字节上限。控制平面的载荷都是小对象，64 KiB 足够。 */
export const MAX_BODY_BYTES = 64 * 1024;

/** 一次性启动令牌的有效期。 */
export const BOOTSTRAP_TTL_MS = 5 * 60 * 1000;

/**
 * 会话的绝对有效期。**不可续期**（续期只延长空闲期限）。
 *
 * 2 小时是一个取舍：控制台要做的事（看一份差异、批准、恢复）都在几分钟内完成，
 * 而操作者离开电脑一次就可能是一下午。绝对上限存在的意义是
 * 「忘了关的浏览器标签页不会在第二天仍然是一座能批准写入的门」。
 */
export const SESSION_TTL_MS = 2 * 60 * 60 * 1000;

/** 空闲有效期。每次成功鉴权的请求会把它推后。 */
export const SESSION_IDLE_TTL_MS = 15 * 60 * 1000;

/**
 * 一次性操作 nonce 的有效期。
 *
 * 取 10 分钟与方案的「本地批准有效期 10 分钟」一致（§9.3）：
 * nonce 的作用是绑定「操作者看到的那一份内容」，
 * 因此它的有效期不该超过那次判断本身的有效期。
 */
export const NONCE_TTL_MS = 10 * 60 * 1000;

/** 同时存在的会话数上限。单用户单控制台，留一点余量给多标签页。 */
export const MAX_SESSIONS = 8;
